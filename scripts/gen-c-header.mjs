#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const input=resolve(process.argv[2]||'')
if(!process.argv[2])throw new Error('usage: gen-c-header.mjs input.nqr [output.h]')
const output=resolve(process.argv[3]||input.replace(/\.nqr$/i,'.h'))
const source=await readFile(input,'utf8')
const map=new Map([
 ['void','void'],['bool','bool'],['i8','int8_t'],['u8','uint8_t'],['i16','int16_t'],['u16','uint16_t'],['i32','int32_t'],['u32','uint32_t'],['i64','int64_t'],['u64','uint64_t'],['isize','intptr_t'],['usize','uintptr_t'],['int','int64_t'],['float','double']
])
function cType(type){
  let raw=type.trim()
  if(raw.startsWith('*'))return `${cType(raw.slice(1))}*`
  const mapped=map.get(raw)
  if(!mapped)throw new Error(`unsupported FFI type ${JSON.stringify(raw)}; use an explicit ABI adapter for strings, slices or records`)
  return mapped
}
const declarations=[]
const rx=/\bexport\s+function\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)\s*(?::\s*([^\s{]+))?/g
for(const match of source.matchAll(rx)){
  const name=match[1],params=[]
  for(const item of match[2].split(',').map(x=>x.trim()).filter(Boolean)){
    const p=/^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(.+)$/.exec(item)
    if(!p)throw new Error(`parameter requires explicit FFI type: ${item}`)
    params.push(`${cType(p[2])} ${p[1]}`)
  }
  declarations.push(`${cType(match[3]||'void')} ${name}(${params.length?params.join(', '):'void'});`)
}
if(!declarations.length)throw new Error('no exported functions found')
const guard=`NOQERI_GENERATED_${input.replace(/[^A-Za-z0-9]/g,'_').toUpperCase()}_H`
const header=`/* Generated by Noqeri. Do not edit manually. */\n#ifndef ${guard}\n#define ${guard}\n#include <stdbool.h>\n#include <stdint.h>\n#include <stddef.h>\n#ifdef __cplusplus\nextern "C" {\n#endif\n\n${declarations.join('\n')}\n\n#ifdef __cplusplus\n}\n#endif\n#endif\n`
await writeFile(output,header)
console.log(`${output}: ${declarations.length} declarations`)
