#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

if(!process.argv[2])throw new Error('usage: gen-noqeri-bindings.mjs input.h [output.nqr]')
const input=resolve(process.argv[2]),output=resolve(process.argv[3]||input.replace(/\.(?:h|hpp)$/i,'.nqr'))
let source=await readFile(input,'utf8')
source=source.replace(/\/\*[\s\S]*?\*\//g,' ').replace(/\/\/[^\n]*/g,' ')
const map=new Map([
 ['void','void'],['bool','bool'],['int8_t','i8'],['uint8_t','u8'],['int16_t','i16'],['uint16_t','u16'],['int32_t','i32'],['uint32_t','u32'],['int64_t','i64'],['uint64_t','u64'],['intptr_t','isize'],['uintptr_t','usize'],['double','float']
])
function normalize(type){return type.replace(/\bconst\b/g,'').replace(/\s+/g,' ').trim()}
function nqrType(type){
  let raw=normalize(type),pointers=0
  while(raw.endsWith('*')){pointers++;raw=normalize(raw.slice(0,-1))}
  const mapped=map.get(raw)
  if(!mapped)throw new Error(`unsupported C FFI type ${JSON.stringify(raw)}; write an explicit ABI adapter`)
  return '*'.repeat(pointers)+mapped
}
const declarations=[]
const rx=/\b([A-Za-z_][A-Za-z0-9_\s]*?(?:\s*\*)*)\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(([^;{}]*)\)\s*;/g
for(const match of source.matchAll(rx)){
  if(/\b(typedef|struct|enum|union)\b/.test(match[1]))continue
  const params=[]
  const body=match[3].trim()
  if(body&&body!=='void'){
    for(const item of body.split(',').map(x=>x.trim()).filter(Boolean)){
      if(item.includes('...'))throw new Error(`variadic C function ${match[2]} is not supported by automatic bindings`)
      const p=/^(.+?)([A-Za-z_][A-Za-z0-9_]*)$/.exec(item)
      if(!p)throw new Error(`cannot parse C parameter ${JSON.stringify(item)}`)
      params.push(`${p[2]}: ${nqrType(p[1])}`)
    }
  }
  declarations.push(`extern function ${match[2]}(${params.join(', ')}): ${nqrType(match[1])}`)
}
if(!declarations.length)throw new Error('no supported C function declarations found')
const text=`// Generated by Noqeri. Raw native calls are unsafe; wrap these declarations in a narrow safe API.\nmodule generated.ffi\n\n${declarations.join('\n')}\n`
await writeFile(output,text)
console.log(`${output}: ${declarations.length} declarations`)
